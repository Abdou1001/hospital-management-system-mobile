import {z} from "zod";

import {GENDER} from "@/types/enums";

/* ============================================================
   Create Doctor Schema
   يستخدم فقط لإنشاء الطبيب
   ولا يحتوي على الدوامات لأنها تُنشأ عبر API مستقل
============================================================ */

export const createDoctorSchema = z.object({
    /* =========================
       اسم الطبيب
    ========================= */
    full_name: z
        .string()
        .trim()
        .min(3, "اسم الطبيب يجب أن يكون 3 أحرف على الأقل")
        .max(100, "اسم الطبيب طويل جدًا"),

    /* =========================
       نبذة عن الطبيب
    ========================= */
    bio: z.string().trim().min(3, "النبذة مطلوبة").max(500).optional(),

    /* =========================
       المؤهل العلمي
    ========================= */
    education: z
        .string()
        .trim()
        .min(3, "المؤهل العلمي مطلوب")
        .max(255)
        .optional(),

    /* =========================
       الجنس
    ========================= */
    gender: z.enum(GENDER),

    /* =========================
       الأقسام المختارة
    ========================= */
    department_ids: z.array(z.number()).min(1, "يجب اختيار قسم واحد على الأقل"),

    /* =========================
       البريد الإلكتروني
    ========================= */
    email: z
        .union([
            z.literal(""),
            z.string().email("البريد الإلكتروني غير صالح").trim(),
        ])
        .optional(),

    /* =========================
       رقم الهاتف
    ========================= */
    phone_number: z
        .string()
        .trim()
        .min(7, "رقم الهاتف غير صالح")
        .max(20)
        .optional(),

    /* =========================
       سنوات الخبرة
    ========================= */
    years_exper: z.coerce
        .number()
        .int()
        .min(0, "سنوات الخبرة غير صحيحة")
        .optional(),

    /* =========================
       رسوم الكشف
    ========================= */
    consultation_fee: z.coerce.number().min(0, "رسوم الكشف غير صحيحة"),

    /* =========================
       ملاحظات
    ========================= */
    notes: z.string().trim().max(500).optional(),

    /* =========================
       صورة الطبيب
    ========================= */
    path_image: z
        .instanceof(File, {
            message: "يرجى اختيار صورة الطبيب",
        })
        .optional(),
});

export type CreateDoctorValues = z.infer<typeof createDoctorSchema>;
